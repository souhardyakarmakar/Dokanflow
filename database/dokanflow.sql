-- DokanFlow schema for local XAMPP development.
-- Import this file into phpMyAdmin to create the database and current schema.
CREATE DATABASE IF NOT EXISTS dokanflow
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE dokanflow;

CREATE TABLE users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(32) NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    last_login_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_public_id (public_id),
    UNIQUE KEY uq_users_email (email),
    CONSTRAINT chk_users_status CHECK (status IN ('active', 'pending', 'suspended'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE businesses (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    slug VARCHAR(100) NOT NULL,
    name VARCHAR(160) NOT NULL,
    legal_name VARCHAR(180) NULL,
    email VARCHAR(254) NULL,
    phone VARCHAR(32) NULL,
    address_line VARCHAR(255) NULL,
    city VARCHAR(100) NULL,
    state VARCHAR(100) NULL,
    postal_code VARCHAR(16) NULL,
    country_code CHAR(2) NOT NULL DEFAULT 'IN',
    gstin VARCHAR(20) NULL,
    gst_registered TINYINT(1) NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_businesses_public_id (public_id),
    UNIQUE KEY uq_businesses_slug (slug),
    UNIQUE KEY uq_businesses_gstin (gstin),
    CONSTRAINT chk_businesses_status CHECK (status IN ('active', 'suspended', 'closed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE business_members (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    business_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    role VARCHAR(24) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    invited_by_user_id BIGINT UNSIGNED NULL,
    invited_at TIMESTAMP NULL DEFAULT NULL,
    accepted_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_business_members_business_user (business_id, user_id),
    KEY idx_business_members_user_status (user_id, status),
    CONSTRAINT chk_business_members_role CHECK (role IN ('owner', 'administrator', 'manager', 'staff')),
    CONSTRAINT chk_business_members_status CHECK (status IN ('invited', 'active', 'suspended', 'removed')),
    CONSTRAINT fk_business_members_business FOREIGN KEY (business_id) REFERENCES businesses (id) ON DELETE RESTRICT,
    CONSTRAINT fk_business_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_business_members_inviter FOREIGN KEY (business_id, invited_by_user_id) REFERENCES business_members (business_id, user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE business_settings (
    business_id BIGINT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Kolkata',
    locale VARCHAR(16) NOT NULL DEFAULT 'en-IN',
    default_gst_rate DECIMAL(5,2) NOT NULL DEFAULT 18.00,
    invoice_prefix VARCHAR(20) NOT NULL DEFAULT 'INV',
    next_invoice_number BIGINT UNSIGNED NOT NULL DEFAULT 1,
    payment_terms_days SMALLINT UNSIGNED NOT NULL DEFAULT 15,
    invoice_footer VARCHAR(500) NULL,
    notifications_enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (business_id),
    CONSTRAINT chk_business_settings_gst CHECK (default_gst_rate >= 0 AND default_gst_rate <= 100),
    CONSTRAINT fk_business_settings_business FOREIGN KEY (business_id) REFERENCES businesses (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE customers (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    business_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(160) NOT NULL,
    customer_type VARCHAR(16) NOT NULL DEFAULT 'individual',
    phone VARCHAR(32) NULL,
    email VARCHAR(254) NULL,
    address_line VARCHAR(255) NULL,
    city VARCHAR(100) NULL,
    state VARCHAR(100) NULL,
    postal_code VARCHAR(16) NULL,
    credit_limit DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    notes TEXT NULL,
    archived_at TIMESTAMP NULL DEFAULT NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_customers_public_id (public_id),
    UNIQUE KEY uq_customers_business_id (business_id, id),
    UNIQUE KEY uq_customers_business_email (business_id, email),
    KEY idx_customers_business_name (business_id, name),
    KEY idx_customers_business_phone (business_id, phone),
    KEY idx_customers_business_type (business_id, customer_type),
    CONSTRAINT chk_customers_type CHECK (customer_type IN ('individual', 'business')),
    CONSTRAINT chk_customers_credit_limit CHECK (credit_limit >= 0),
    CONSTRAINT fk_customers_business FOREIGN KEY (business_id) REFERENCES businesses (id) ON DELETE RESTRICT,
    CONSTRAINT fk_customers_creator FOREIGN KEY (business_id, created_by_user_id) REFERENCES business_members (business_id, user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    business_id BIGINT UNSIGNED NOT NULL,
    customer_id BIGINT UNSIGNED NOT NULL,
    order_number VARCHAR(40) NOT NULL,
    service_description VARCHAR(500) NOT NULL,
    estimated_amount DECIMAL(15,2) NOT NULL,
    order_date DATE NOT NULL,
    expected_delivery_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'received',
    notes TEXT NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_orders_public_id (public_id),
    UNIQUE KEY uq_orders_business_number (business_id, order_number),
    UNIQUE KEY uq_orders_business_id_customer (business_id, id, customer_id),
    KEY idx_orders_business_status_date (business_id, status, order_date),
    KEY idx_orders_business_customer (business_id, customer_id),
    KEY idx_orders_business_delivery (business_id, expected_delivery_date),
    CONSTRAINT chk_orders_status CHECK (status IN ('received', 'in_progress', 'ready', 'delivered', 'cancelled')),
    CONSTRAINT chk_orders_estimated_amount CHECK (estimated_amount >= 0),
    CONSTRAINT chk_orders_delivery_dates CHECK (expected_delivery_date >= order_date),
    CONSTRAINT fk_orders_business FOREIGN KEY (business_id) REFERENCES businesses (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_customer FOREIGN KEY (business_id, customer_id) REFERENCES customers (business_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_creator FOREIGN KEY (business_id, created_by_user_id) REFERENCES business_members (business_id, user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE invoices (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    business_id BIGINT UNSIGNED NOT NULL,
    customer_id BIGINT UNSIGNED NOT NULL,
    order_id BIGINT UNSIGNED NULL,
    invoice_number VARCHAR(40) NOT NULL,
    issue_date DATE NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'issued',
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    gst_enabled TINYINT(1) NOT NULL DEFAULT 1,
    discount_rate DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    subtotal DECIMAL(15,2) NOT NULL,
    discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(15,2) NOT NULL,
    business_snapshot JSON NOT NULL,
    customer_snapshot JSON NOT NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    issued_at TIMESTAMP NULL DEFAULT NULL,
    voided_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_invoices_public_id (public_id),
    UNIQUE KEY uq_invoices_business_number (business_id, invoice_number),
    UNIQUE KEY uq_invoices_business_id (business_id, id),
    UNIQUE KEY uq_invoices_business_order (business_id, order_id),
    KEY idx_invoices_business_customer_date (business_id, customer_id, issue_date),
    KEY idx_invoices_business_due_status (business_id, due_date, status),
    CONSTRAINT chk_invoices_status CHECK (status IN ('draft', 'issued', 'void')),
    CONSTRAINT chk_invoices_amounts CHECK (subtotal >= 0 AND discount_amount >= 0 AND tax_amount >= 0 AND total_amount >= 0),
    CONSTRAINT chk_invoices_discount_rate CHECK (discount_rate >= 0 AND discount_rate <= 100),
    CONSTRAINT chk_invoices_due_date CHECK (due_date >= issue_date),
    CONSTRAINT fk_invoices_business FOREIGN KEY (business_id) REFERENCES businesses (id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoices_customer FOREIGN KEY (business_id, customer_id) REFERENCES customers (business_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoices_order_customer FOREIGN KEY (business_id, order_id, customer_id) REFERENCES orders (business_id, id, customer_id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoices_creator FOREIGN KEY (business_id, created_by_user_id) REFERENCES business_members (business_id, user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE invoice_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    business_id BIGINT UNSIGNED NOT NULL,
    invoice_id BIGINT UNSIGNED NOT NULL,
    line_number SMALLINT UNSIGNED NOT NULL,
    description VARCHAR(500) NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    unit_price DECIMAL(15,2) NOT NULL,
    gst_rate DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    line_subtotal DECIMAL(15,2) NOT NULL,
    discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    taxable_amount DECIMAL(15,2) NOT NULL,
    tax_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    line_total DECIMAL(15,2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_invoice_items_public_id (public_id),
    UNIQUE KEY uq_invoice_items_business_line (business_id, invoice_id, line_number),
    KEY idx_invoice_items_business_invoice (business_id, invoice_id),
    CONSTRAINT chk_invoice_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_invoice_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_invoice_items_gst CHECK (gst_rate >= 0 AND gst_rate <= 100),
    CONSTRAINT chk_invoice_items_amounts CHECK (line_subtotal >= 0 AND discount_amount >= 0 AND taxable_amount >= 0 AND tax_amount >= 0 AND line_total >= 0),
    CONSTRAINT fk_invoice_items_invoice FOREIGN KEY (business_id, invoice_id) REFERENCES invoices (business_id, id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    business_id BIGINT UNSIGNED NOT NULL,
    invoice_id BIGINT UNSIGNED NOT NULL,
    amount DECIMAL(15,2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    method VARCHAR(24) NOT NULL,
    status VARCHAR(16) NOT NULL,
    reference VARCHAR(120) NULL,
    provider VARCHAR(24) NULL,
    gateway_order_id VARCHAR(100) NULL,
    gateway_payment_id VARCHAR(100) NULL,
    idempotency_key VARCHAR(100) NULL,
    received_at TIMESTAMP NULL DEFAULT NULL,
    recorded_by_user_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_payments_public_id (public_id),
    UNIQUE KEY uq_payments_business_idempotency (business_id, idempotency_key),
    UNIQUE KEY uq_payments_gateway_order (provider, gateway_order_id),
    UNIQUE KEY uq_payments_gateway_payment (provider, gateway_payment_id),
    KEY idx_payments_business_invoice_status (business_id, invoice_id, status),
    KEY idx_payments_business_received (business_id, received_at),
    CONSTRAINT chk_payments_amount CHECK (amount > 0),
    CONSTRAINT chk_payments_method CHECK (method IN ('upi', 'cash', 'bank_transfer', 'card', 'razorpay', 'other')),
    CONSTRAINT chk_payments_status CHECK (status IN ('pending', 'captured', 'failed', 'refunded')),
    CONSTRAINT fk_payments_invoice FOREIGN KEY (business_id, invoice_id) REFERENCES invoices (business_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_recorder FOREIGN KEY (business_id, recorded_by_user_id) REFERENCES business_members (business_id, user_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

